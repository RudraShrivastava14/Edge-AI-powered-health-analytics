"""Generate the figures embedded in the root README.

Every figure here is produced from **real output of the code in this repository** — the
edge simulator and the uplink policy — not from mock data. Regenerate with:

    pip install numpy matplotlib
    python results/figures/make_figures.py

Note: the anomaly scorer is currently the placeholder heuristic in
``edge/edge_inference/policy.score_window`` (task M-6b), not the trained TFLite model.
Figures are labelled accordingly. Re-run this after M-5 lands and update the captions.
"""

from __future__ import annotations

import pathlib
import sys

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "edge"))

from edge_inference import policy                      # noqa: E402
from simulator.generator import generate_stream, generate_window  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parent
SEED = 7

# Restrained, colour-blind-safe palette. Severity is never encoded by colour alone.
INK = "#1c2024"
MUTED = "#6b7280"
GRID = "#e5e7eb"
NORMAL = "#2f7d68"
SUSPECT = "#c8850a"
CRITICAL = "#c0392b"
ACCENT = "#2563a8"

plt.rcParams.update({
    "figure.facecolor": "white",
    "axes.facecolor": "white",
    "axes.edgecolor": GRID,
    "axes.labelcolor": INK,
    "axes.titlecolor": INK,
    "text.color": INK,
    "xtick.color": MUTED,
    "ytick.color": MUTED,
    "grid.color": GRID,
    "font.size": 9,
    "axes.titlesize": 10,
    "axes.titleweight": "600",
    "axes.spines.top": False,
    "axes.spines.right": False,
    "figure.dpi": 200,
})

FLAG_COLOUR = {
    policy.Flag.NORMAL: NORMAL,
    policy.Flag.SUSPECT: SUSPECT,
    policy.Flag.CRITICAL: CRITICAL,
}


def fig_ecg_profiles() -> None:
    """Synthesised ECG for four profiles, with the edge verdict for each."""
    profiles = ["healthy", "tachycardia", "bradycardia", "arrhythmia"]
    thresholds = policy.Thresholds()
    rng = np.random.default_rng(SEED)

    fig, axes = plt.subplots(len(profiles), 1, figsize=(9, 6.2), sharex=True)
    for ax, prof in zip(axes, profiles):
        win = generate_window(prof, rng=rng)
        err, _ = policy.score_window(win)
        flag = policy.classify(err, win.activity, thresholds)
        colour = FLAG_COLOUR[flag]

        t = np.arange(win.ecg.size) / 125.0
        ax.plot(t, win.ecg, lw=0.7, color=colour)
        ax.set_ylabel("mV\n(norm.)", fontsize=8)
        ax.grid(axis="y", lw=0.5)
        ax.set_xlim(0, 10)

        hr = win.hr_stats
        ax.set_title(
            f"{prof}   ·   HR {hr['mean']:.0f} bpm   ·   SpO₂ {win.spo2:.1f}%   ·   "
            f"activity: {win.activity}   ·   error {err:.3f}   →   {flag.value.upper()}",
            loc="left", color=colour,
        )

    axes[-1].set_xlabel("time (s)  —  one 10-second window at 125 Hz")
    fig.suptitle(
        "Synthesised wearable ECG and the edge verdict per profile",
        x=0.012, ha="left", fontsize=12, fontweight="600",
    )
    fig.text(
        0.012, 0.005,
        "Generated by edge/simulator/generator.py + edge/edge_inference/policy.py  ·  "
        "scorer: placeholder heuristic (task M-6b), not the trained model",
        fontsize=7.5, color=MUTED,
    )
    fig.tight_layout(rect=(0, 0.025, 1, 0.955))
    fig.savefig(OUT / "sim_ecg_profiles.png", bbox_inches="tight")
    plt.close(fig)


def run_stream(n: int = 400):
    """Run the simulator and collect per-window results."""
    thresholds = policy.Thresholds()
    rows = []
    for i, win in enumerate(generate_stream("mixed", n_windows=n, seed=SEED)):
        err, inf_ms = policy.score_window(win)
        flag = policy.classify(err, win.activity, thresholds)
        payload = policy.build_payload(
            device_id="demo-001", ts_ms=1753900000000 + i * 10_000, seq=i,
            window=win, recon_error=err, flag=flag, inference_ms=inf_ms,
        )
        rows.append({
            "i": i,
            "err": err,
            "flag": flag,
            "activity": win.activity,
            "anomalous": win.anomalous,
            "hr": win.hr_stats["mean"],
            "sent": policy.payload_bytes(payload),
            "baseline": policy.baseline_bytes(win),
        })
    return rows, thresholds


def fig_cascade_timeline(rows, thresholds) -> None:
    """Reconstruction error over time against the escalation thresholds."""
    fig, (ax, ax2) = plt.subplots(
        2, 1, figsize=(10, 5.0), sharex=True, gridspec_kw={"height_ratios": [3, 1]}
    )

    idx = np.array([r["i"] for r in rows])
    err = np.array([r["err"] for r in rows])

    # Shade the ground-truth abnormal episodes.
    anom = np.array([r["anomalous"] for r in rows])
    start = None
    for i, a in enumerate([*anom, False]):
        if a and start is None:
            start = i
        elif not a and start is not None:
            ax.axvspan(start - 0.5, i - 0.5, color=CRITICAL, alpha=0.07, lw=0)
            ax2.axvspan(start - 0.5, i - 0.5, color=CRITICAL, alpha=0.07, lw=0)
            start = None

    ax.axhline(thresholds.tau_low, color=SUSPECT, lw=1, ls="--")
    ax.axhline(thresholds.tau_high, color=CRITICAL, lw=1, ls="--")
    ax.text(len(rows) * 0.995, thresholds.tau_low, r"  $\tau_{low}$",
            color=SUSPECT, va="center", fontsize=8)
    ax.text(len(rows) * 0.995, thresholds.tau_high, r"  $\tau_{high}$",
            color=CRITICAL, va="center", fontsize=8)

    ax.plot(idx, err, lw=0.8, color=MUTED, alpha=0.7, zorder=1)
    for flag in (policy.Flag.NORMAL, policy.Flag.SUSPECT, policy.Flag.CRITICAL):
        sel = [r for r in rows if r["flag"] is flag]
        if sel:
            ax.scatter([r["i"] for r in sel], [r["err"] for r in sel], s=11,
                       color=FLAG_COLOUR[flag], zorder=3, label=flag.value)

    ax.set_ylabel("reconstruction error")
    ax.grid(axis="y", lw=0.5)
    ax.legend(loc="upper left", frameon=False, ncols=3, fontsize=8)
    ax.set_title(
        "Edge screening over a 400-window run (≈67 min): only escalated windows "
        "upload a waveform",
        loc="left",
    )

    sent = np.array([r["sent"] for r in rows]) / 1024.0
    ax2.bar(idx, sent, width=1.0,
            color=[FLAG_COLOUR[r["flag"]] for r in rows], linewidth=0)
    ax2.set_ylabel("uplink\n(KB)", fontsize=8)
    ax2.set_xlabel("window index  (one 10-second window each)")
    ax2.grid(axis="y", lw=0.5)
    ax2.set_xlim(-2, len(rows) + 1)

    fig.text(
        0.012, 0.005,
        "Shaded bands = ground-truth abnormal episodes  ·  "
        "scorer: placeholder heuristic (task M-6b), not the trained model",
        fontsize=7.5, color=MUTED,
    )
    fig.tight_layout(rect=(0, 0.03, 1, 1))
    fig.savefig(OUT / "sim_cascade_timeline.png", bbox_inches="tight")
    plt.close(fig)


def fig_bandwidth(rows) -> None:
    """Measured uplink volume against the stream-everything baseline."""
    sent = sum(r["sent"] for r in rows) / 1024.0
    base = sum(r["baseline"] for r in rows) / 1024.0
    reduction = (1 - sent / base) * 100

    counts = {f: sum(1 for r in rows if r["flag"] is f) for f in policy.Flag}

    fig, (ax, ax2) = plt.subplots(1, 2, figsize=(9.5, 3.4),
                                  gridspec_kw={"width_ratios": [1.25, 1]})

    bars = ax.barh(["stream everything\n(baseline)", "edge-filtered\n(this project)"],
                   [base, sent], color=[MUTED, ACCENT], height=0.5)
    for b, v in zip(bars, [base, sent]):
        ax.text(v + base * 0.015, b.get_y() + b.get_height() / 2,
                f"{v:,.0f} KB", va="center", fontsize=9, color=INK)
    ax.set_xlim(0, base * 1.22)
    ax.set_xlabel("uplink volume over 400 windows (KB)")
    ax.grid(axis="x", lw=0.5)
    ax.set_title(f"{reduction:.1f}% less data sent", loc="left", color=ACCENT)

    labels = [f.value for f in policy.Flag]
    values = [counts[f] for f in policy.Flag]
    ax2.bar(labels, values, color=[FLAG_COLOUR[f] for f in policy.Flag], width=0.55)
    for i, v in enumerate(values):
        ax2.text(i, v + max(values) * 0.02, str(v), ha="center", fontsize=9)
    ax2.set_ylabel("windows")
    ax2.grid(axis="y", lw=0.5)
    ax2.set_ylim(0, max(values) * 1.16)
    ax2.set_title("edge verdicts", loc="left")

    fig.text(
        0.012, 0.005,
        "Baseline compresses raw float32 ECG with zlib, so the comparison is not rigged  ·  "
        "scorer: placeholder heuristic (task M-6b)",
        fontsize=7.5, color=MUTED,
    )
    fig.tight_layout(rect=(0, 0.05, 1, 1))
    fig.savefig(OUT / "sim_bandwidth.png", bbox_inches="tight")
    plt.close(fig)

    print(f"  bandwidth: sent {sent:,.0f} KB vs baseline {base:,.0f} KB "
          f"= {reduction:.1f}% reduction")
    print(f"  flags: { {f.value: counts[f] for f in policy.Flag} }")


def main() -> int:
    print("generating figures from live simulator output …")
    fig_ecg_profiles()
    print("  wrote sim_ecg_profiles.png")
    rows, thresholds = run_stream(400)
    fig_cascade_timeline(rows, thresholds)
    print("  wrote sim_cascade_timeline.png")
    fig_bandwidth(rows)
    print("  wrote sim_bandwidth.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
